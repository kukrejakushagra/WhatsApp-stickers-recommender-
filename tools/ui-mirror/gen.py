#!/usr/bin/env python3
"""Generates a web copy of the app's design tokens and icons, straight from the Kotlin and XML sources.

Output (stdout): one CSS block (light tokens on .kds-light, dark on .kds-dark, type scale classes)
followed by a <svg> sprite with every ic_kds_* icon as a <symbol id="i-NAME">. Paste it into a web
mock-up of the app so its colours, type and icons stay identical to the app's.

    python3 tools/ui-mirror/gen.py > tokens.html
"""
import pathlib, re, sys, xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[2] / "app/src/main"
KDS = ROOT / "java/app/stickersearch/ui/kds/theme"
A = "{http://schemas.android.com/apk/res/android}"


def kebab(name):
    return re.sub(r"(?<=[a-z0-9])([A-Z0-9])", r"-\1", name).lower()


def rgba(argb):
    a, r, g, b = (int(argb[i:i + 2], 16) for i in (0, 2, 4, 6))
    return f"#{r:02x}{g:02x}{b:02x}" if a == 255 else f"rgba({r},{g},{b},{a / 255:.3f})"


def colours():
    src = (KDS / "Colors.kt").read_text()
    out = []
    for theme in ("Light", "Dark"):
        block = re.search(rf"Kds{theme}Colors = KdsColors\((.*?)\n\)", src, re.S).group(1)
        pairs = re.findall(r"(\w+) = Color\(0x([0-9A-Fa-f]{8})\)", block)
        body = "".join(f"--{kebab(n)}:{rgba(v)};" for n, v in pairs)
        out.append(f".kds-{theme.lower()}{{{body}color-scheme:{theme.lower()}}}")
    return "\n".join(out)


def typescale():
    src = (KDS / "KdsTheme.kt").read_text()
    out = []
    for name, args in re.findall(r"(\w+) = style\(([^)]*)\)", src):
        parts = [p.strip() for p in args.split(",")]
        size, line, weight = parts[0], parts[1], parts[2]
        track = next((p for p in parts[3:] if re.match(r"^-?\d*\.\d+$", p)), None)
        tab = any("tabular = true" in p for p in parts)
        css = f"font-size:{size}px;line-height:{line}px;font-weight:{weight};"
        if track: css += f"letter-spacing:{track}em;"
        if tab: css += "font-feature-settings:'tnum';"
        out.append(f".t-{kebab(name)}{{{css}}}")
    out.append(".t-mono{font-family:ui-monospace,'Geist Mono',monospace;font-size:12px;line-height:16px}")
    return "\n".join(out)


def icons():
    syms = []
    for f in sorted((ROOT / "res/drawable").glob("ic_kds_*.xml")):
        root = ET.parse(f).getroot()
        vb = f"0 0 {root.get(A + 'viewportWidth')} {root.get(A + 'viewportHeight')}"
        paths = []
        for p in root.iter("path"):
            d = p.get(A + "pathData")
            stroke = p.get(A + "strokeColor") not in (None, "#00000000")
            fill = p.get(A + "fillColor") not in (None, "#00000000")
            attrs = [f'd="{d}"']
            attrs.append('fill="currentColor"' if fill else 'fill="none"')
            if stroke:
                attrs.append(f'stroke="currentColor" stroke-width="{p.get(A + "strokeWidth", "2")}" '
                             f'stroke-linecap="{p.get(A + "strokeLineCap", "round")}" stroke-linejoin="{p.get(A + "strokeLineJoin", "round")}"')
            paths.append(f"<path {' '.join(attrs)}/>")
        syms.append(f'<symbol id="i-{f.stem.removeprefix("ic_kds_")}" viewBox="{vb}">{"".join(paths)}</symbol>')
    return '<svg width="0" height="0" style="position:absolute" aria-hidden="true">' + "".join(syms) + "</svg>"


if __name__ == "__main__":
    sys.stdout.write("<style>\n/* generated by tools/ui-mirror/gen.py: do not edit by hand */\n"
                     + colours() + "\n" + typescale() + "\n</style>\n" + icons() + "\n")
